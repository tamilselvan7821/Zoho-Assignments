/*
Write a program to find the maximum of two numbers using the ternary operator.
*/
public class MaximumTwoNumber{
    public static void main(String[] args) {
        int appleRate=10;
        int orangeRate=5;
        int maximumRate=(appleRate>orangeRate)?appleRate:orangeRate;
        //print maximum value of apple=10
        System.out.println(maximumRate);
    }
}